@st.cache_data(ttl=60)
def get_df(sym, p, iv):
    try:
        df = yf.download(sym, period=p, interval="1h" if iv=="4h" else iv, progress=False)
        if df is None or df.empty:
            df = yf.download(sym, period="3mo", interval="1d", progress=False)
        if df is None or df.empty:
            return pd.DataFrame()
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)
        df = df[['Open', 'High', 'Low', 'Close']].dropna()
        if iv == "4h" and len(df) > 20:
            r = df.resample("4h").agg({"Open":"first","High":"max","Low":"min","Close":"last"}).dropna()
            return r if len(r) >= 15 else df
        return df
    except Exception:
        return pd.DataFrame()

def trend(df):
    if len(df) < 15:
        return "N/A"
    e20 = float(df['Close'].ewm(span=min(20, len(df))).mean().iloc[-1])
    e50 = float(df['Close'].ewm(span=min(50, len(df))).mean().iloc[-1])
    c = float(df['Close'].iloc[-1])
    return "🟢 Bullish" if c > e20 > e50 else ("🔴 Bearish" if c < e20 < e50 else "🟡 Ranging")

def get_rsi(df):
    d = df['Close'].diff()
    g = d.where(d > 0, 0).rolling(14).mean()
    l = (-d.where(d < 0, 0)).rolling(14).mean()
    rsi = 100 - (100 / (1 + g / l.replace(0, 1e-10)))
    return round(float(rsi.iloc[-1]), 1) if not pd.isna(rsi.iloc[-1]) else 50.0

def make_fig(df_s, h=400):
    xl = [str(i) for i in df_s.index]
    fig = go.Figure(data=[go.Candlestick(
        x=xl,
        open=df_s['Open'].tolist(),
        high=df_s['High'].tolist(),
        low=df_s['Low'].tolist(),
        close=df_s['Close'].tolist(),
        name="Price"
    )])
    fig.update_layout(
        xaxis_rangeslider_visible=False,
        height=h,
        autosize=True,
        margin=dict(l=10, r=10, t=30, b=10),
        template="plotly_dark",
        xaxis_type="category",
        showlegend=False
    )
    fig.update_xaxes(showticklabels=False)
    return fig, xl

def draw_box(fig, x0, x1, y0, y1, rgba, bcol, lbl):
    fig.add_trace(go.Scatter(
        x=[x0, x1, x1, x0, x0],
        y=[y0, y0, y1, y1, y0],
        fill="toself",
        fillcolor=rgba,
        line=dict(color=bcol, width=1.5),
        mode="lines",
        hoverinfo="skip"
    ))
    fig.add_annotation(
        x=x1,
        y=(y0+y1)/2,
        text=f"<b>{lbl}</b>",
        showarrow=False,
        xanchor="right",
        font=dict(color="white", size=11),
        bgcolor=bcol,
        borderpad=3
    )

def draw_line(fig, x0, x1, yv, col, lbl, dsh="dash"):
    fig.add_trace(go.Scatter(
        x=[x0, x1],
        y=[yv, yv],
        mode="lines",
        line=dict(color=col, width=1.8, dash=dsh)
    ))
    fig.add_annotation(
        x=x0,
        y=yv,
        text=f"<b>{lbl}</b>",
        showarrow=False,
        xanchor="left",
        yshift=11,
        font=dict(color=col, size=11)
    )

